//! `publish <run id>` for a Test run: one zip over the whole run (`embarch-api`
//! decision 144; `embarch-core` decisions 148 to 150).
//!
//! The same two steps as a Study's, over `/test-runs/{id}/...`: `report-data`,
//! the PDF rendered here from it, `publish` with the hashes of what this crate
//! made, then every file the signed manifest names fetched, checked and zipped.
//! The PDF is organised by requirement and reads `report-data.json` and
//! `run.json` only, both served at the pending revision. A Test run has no
//! `report.typ`, notes or prose: Core has no route to adopt them for one.

use std::collections::BTreeMap;
use std::path::Path;

use anyhow::{anyhow, bail, Context, Result};
use embarch_core_client::{CoreClient, PublishFile};
use serde_json::Value;

use crate::publish::{
    manifest_subjects, sha256_hex, slug, utc_date, write_zip, zip_name, PublishOutcome, PublishRequest, JUNIT_NAME, MANIFEST_NAME,
    OCP_NAME, REPORT_DATA_NAME, REPORT_PDF,
};
use crate::publish_test_export::{junit_xml, ocp_jsonl, TestExportInputs};
use crate::publish_report::{at, lit, show, Doc, ReportSource, Supersedes};
use crate::report_pdf::{render_report, RenderOptions, Staging, APPENDIX_FILE, REPORT_FILE, TYPST_VERSION};

/// The run's own record of what it was, served at the pending revision.
pub const RUN_JSON_NAME: &str = "run.json";

/// What a Test run's publish names a request that Core cannot take for one.
const NO_ADOPTION_MESSAGE: &str = "publish refuses: a Test run takes no notes, prose or report.typ. Core has no route to adopt \
them for one, and its report is generated by requirement (embarch-api decision 144); drop those arguments";

/// `verdict`, its qualifiers in words, and "N of M tests run" when the roll-up says some were
/// not. The roll-up is `embarch-study-designer`'s `Requirement`: snake_case qualifiers, and
/// `n_of_m` an object `{n, m}` that travels beside the `n_of_m_run` qualifier.
fn verdict_label(v: &Value) -> String {
    let mut parts = vec![show(&v["verdict"])];
    let n_of_m = v["n_of_m"].as_object().and_then(|o| Some((o.get("n")?.as_u64()?, o.get("m")?.as_u64()?)));
    let n_of_m_text = n_of_m.filter(|(n, m)| n != m).map(|(n, m)| format!("{n} of {m} tests run"));
    for q in v["qualifiers"].as_array().into_iter().flatten() {
        match q.as_str() {
            Some("n_of_m_run") => {}
            Some(s) => parts.push(s.replace('_', " ")),
            None => parts.push(show(q)),
        }
    }
    parts.extend(n_of_m_text);
    parts.join(", ")
}

fn counts_label(v: &Value) -> String {
    match v["counts"].as_object() {
        Some(o) if !o.is_empty() => o.iter().map(|(k, n)| format!("{n} {k}")).collect::<Vec<_>>().join(", "),
        _ => "none".to_string(),
    }
}

/// The report: by requirement, each verdict citing the run behind it.
pub fn report_source(rd: &Value) -> Result<String> {
    let statement = rd["statement"]
        .as_str()
        .filter(|s| !s.trim().is_empty())
        .ok_or_else(|| anyhow!("Core's report-data.json carries no statement, and a Test report never prints without it"))?;
    let run = at(rd, "/run_id");
    let mut d = Doc::new();
    d.0.push_str("#set text(size: 10pt)\n");
    d.0.push_str(&format!("#title({})\n", lit(&format!("Test report: {}", at(rd, "/suite/id")))));
    d.para(statement);
    d.para(&format!(
        "Run {run}, status {}. Suite {} version {} (commit {}). Overall: {}.",
        at(rd, "/run_status"),
        at(rd, "/suite/id"),
        at(rd, "/suite/version"),
        at(rd, "/suite/commit"),
        verdict_label(&rd["summary"]),
    ));

    d.heading(1, "Unit under test");
    d.kv(&[
        ("Hardware ID (unit key)", at(rd, "/unit/unit_key")),
        (
            "Identity read from the chip",
            if rd["unit"]["identity_read"] == true {
                "yes".to_string()
            } else {
                "no: unit identity not read, its history may be split".to_string()
            },
        ),
        ("Declared serial", at(rd, "/unit/declared_serial")),
        ("Board revision", at(rd, "/unit/board_revision")),
        ("Person responsible", at(rd, "/person")),
        ("Go given by", at(rd, "/go_by")),
        ("Published by", at(rd, "/published_by")),
        ("Standard tested against", format!("{} {}", at(rd, "/standard/name"), at(rd, "/standard/revision"))),
    ]);

    d.heading(1, "Requirements");
    let reqs: Vec<Vec<String>> = rd["requirements"]
        .as_object()
        .into_iter()
        .flatten()
        .map(|(id, r)| {
            let skipped: Vec<String> = r["skipped_tests"]
                .as_array()
                .into_iter()
                .flatten()
                .map(|s| format!("{}: {}", show(&s["test_id"]), show(&s["reason"])))
                .collect();
            vec![
                id.clone(),
                verdict_label(r),
                counts_label(r),
                r["tests"].as_array().into_iter().flatten().map(show).collect::<Vec<_>>().join(", "),
                if skipped.is_empty() { "none".to_string() } else { skipped.join("; ") },
            ]
        })
        .collect();
    if reqs.is_empty() {
        d.para("The run's tests name no requirement.");
    } else {
        d.table(&["Requirement", "Verdict", "Counts", "Tests", "Skipped"], &reqs);
    }

    d.heading(1, "Tests");
    let ids: Vec<String> = rd["study_ids"].as_array().into_iter().flatten().map(show).collect();
    d.para(&format!("Every verdict below is the run {run}'s, signed by Core. Study runs: {}.", ids.join(", ")));
    let tests: Vec<Vec<String>> = rd["tests"]
        .as_array()
        .into_iter()
        .flatten()
        .map(|t| {
            vec![
                show(&t["test_id"]),
                verdict_label(t),
                show(&t["reason"]),
                format!("{run}: {}", t["study_ids"].as_array().into_iter().flatten().map(show).collect::<Vec<_>>().join(", ")),
                show(&t["dut_image"]),
            ]
        })
        .collect();
    if tests.is_empty() {
        d.para("No test was judged.");
    } else {
        d.table(&["Test", "Verdict", "Reason", "Behind it (run: study runs)", "DUT image"], &tests);
    }

    d.heading(1, "Tests that did not run");
    let not_run: Vec<Vec<String>> = rd["not_run"]
        .as_array()
        .into_iter()
        .flatten()
        .map(|n| vec![show(&n["test_id"]), show(&n["reason"]), show(&n["source"]), show(&n["status"])])
        .collect();
    if not_run.is_empty() {
        d.para("Every selected test ran.");
    } else {
        d.table(&["Test", "Why", "Listed by", "Selection status"], &not_run);
    }
    d.para(&format!("Coverage as Core's signed selection holds it: {}.", at(rd, "/coverage")));

    d.heading(1, "Every run of each test on this unit");
    d.para("Read from Core's run log, failed runs included, grouped by test, requirement, DUT image and definition hash.");
    let history: Vec<Vec<String>> = rd["runs_on_unit"]
        .as_array()
        .into_iter()
        .flatten()
        .map(|h| {
            let runs: Vec<String> = h["runs"]
                .as_array()
                .into_iter()
                .flatten()
                .map(|r| format!("{} {} (log {})", show(&r["run_id"]), show(&r["verdict"]), show(&r["log_index"])))
                .collect();
            vec![
                show(&h["test_id"]),
                h["requirements"].as_array().into_iter().flatten().map(show).collect::<Vec<_>>().join(", "),
                show(&h["dut_image"]),
                show(&h["definition_hash"]),
                runs.join("; "),
            ]
        })
        .collect();
    if history.is_empty() {
        d.para("No earlier run of these tests is on this unit's log.");
    } else {
        d.table(&["Test", "Requirements", "DUT image", "Definition hash", "Runs"], &history);
    }

    d.heading(1, "Decision rule");
    d.para("The roll-up rules Core applied to the tests' verdicts. The limit and decision rule of each individual test (simple acceptance or a guard band) are not carried in report-data.json, so this report does not state them per limit.");
    let rules: Vec<Vec<String>> =
        rd["rules"].as_array().into_iter().flatten().map(|r| vec![show(&r["name"]), show(&r["behaviour"])]).collect();
    if !rules.is_empty() {
        d.table(&["Rule", "Behaviour"], &rules);
    }
    Ok(d.0)
}

/// What the appendix pins about the run: `run.json`'s hash, the plan's and the suite's.
pub struct RunPins<'a> {
    pub run_json_sha256: &'a str,
    pub plan_hash: Option<&'a str>,
    pub revision: u64,
    pub supersedes: Option<&'a Supersedes>,
}

/// The audit appendix of a Test run's report, as Typst string literals.
pub fn appendix_source(rd: &Value, pins: &RunPins) -> String {
    let mut d = Doc::new();
    d.0.push_str("#set text(size: 9pt)\n");
    d.heading(1, "Audit appendix");
    d.para("Appended by embarch-api to every report. Core's signed manifest lists every file of this zip it produced; the files embarch-api made are listed in it as embarch-api's and are checked by verify, not by Core's signature.");
    d.heading(2, "Observed by Core");
    let mut observed = vec![
        ("Run", at(rd, "/run_id")),
        ("Run status", at(rd, "/run_status")),
        ("Reason", at(rd, "/reason")),
        ("Resumes", at(rd, "/resumes")),
        ("Summary", verdict_label(&rd["summary"])),
        ("Study runs", at(rd, "/study_ids")),
    ];
    observed.extend(crate::publish_report::call_log_rows(rd));
    observed.extend([
        ("Core version", at(rd, "/core/version")),
        ("Core key id", at(rd, "/core/keyid")),
        ("Signed record SHA-256", at(rd, "/record_sha256")),
    ]);
    d.kv(&observed);
    d.heading(2, "Pinned inputs");
    d.kv(&[
        ("run.json SHA-256", pins.run_json_sha256.to_string()),
        ("Plan hash", pins.plan_hash.unwrap_or("none (the run named no plan)").to_string()),
        ("Suite", format!("{} version {} commit {}", at(rd, "/suite/id"), at(rd, "/suite/version"), at(rd, "/suite/commit"))),
        ("Revision", pins.revision.to_string()),
        ("embarch-api version", env!("CARGO_PKG_VERSION").to_string()),
        ("Typst version", TYPST_VERSION.to_string()),
        ("report.typ", ReportSource::Generated.as_str().to_string()),
    ]);
    d.heading(2, "Attestation");
    d.kv(&[
        ("Label", at(rd, "/attestation/label")),
        ("Core attested", at(rd, "/attestation/core_attested")),
        ("Reason", at(rd, "/attestation/reason")),
        ("Run begun with", at(rd, "/go_by")),
        ("Published by", at(rd, "/published_by")),
    ]);
    d.heading(2, "Manual verdicts");
    let manual: Vec<Vec<String>> = rd["manual_verdicts"]
        .as_array()
        .into_iter()
        .flatten()
        .map(|m| {
            vec![
                show(&m["test_id"]),
                show(&m["verdict"]),
                show(&m["attribution"]),
                show(&m["relayed"]),
                show(&m["counted"]),
                show(&m["in_run"]),
            ]
        })
        .collect();
    if manual.is_empty() {
        d.para("No manual verdict was entered on this unit.");
    } else {
        d.table(&["Test", "Verdict", "Attribution", "Relayed", "Counted", "In this run"], &manual);
    }
    d.heading(2, "Limits and losses");
    d.para(&format!(
        "Not carried in this report: the standard's requirement count ({}: Core joins no atlas), per-limit decision rules, a resumed pair published as one.",
        at(rd, "/standard/requirement_count")
    ));
    d.heading(2, "Hash manifest");
    d.para(&format!("manifest.dsse.json, signed by Core, holds the SHA-256 of every file of this zip it produced. This is revision {}.", pins.revision));
    match pins.supersedes {
        None => d.para("It supersedes no earlier revision."),
        Some(s) => {
            let hash = match &s.manifest_sha256 {
                Some(h) => format!("Core's manifest for it hashes to {h}"),
                None => "Core did not supply its manifest, so no hash is recorded".to_string(),
            };
            d.para(&format!("It supersedes revision {}: {hash}.", s.revision));
        }
    }
    d.0
}

/// The study runs `report-data.json` names, each once.
fn study_ids_of(rd: &Value) -> Vec<String> {
    let mut ids: Vec<String> = rd["tests"]
        .as_array()
        .into_iter()
        .flatten()
        .flat_map(|t| t["study_ids"].as_array().into_iter().flatten())
        .filter_map(|s| s.as_str().map(str::to_string))
        .collect();
    ids.sort();
    ids.dedup();
    ids
}

/// Runs a Test run's publish. `folder` and `now_unix` are the Study's.
pub async fn run(core: &CoreClient, folder: &Path, req: &PublishRequest<'_>, now_unix: i64) -> Result<PublishOutcome> {
    if req.notes.is_some_and(|n| !n.trim().is_empty()) || !req.prose.is_empty() || req.report_typ.is_some() {
        bail!(NO_ADOPTION_MESSAGE);
    }
    let run_id = req.run_id;

    let rd = core.test_report_data(run_id).await.context("Core refused the Test run's report-data")?;
    let revision = rd.revision;
    let pending = |name: &'static str| async move {
        core.test_publish_file(run_id, revision, name)
            .await?
            .ok_or_else(|| anyhow!("Core did not serve {name} for revision {revision}"))
    };
    let report_data_bytes = pending(REPORT_DATA_NAME).await?;
    if sha256_hex(&report_data_bytes) != rd.report_data_sha256 {
        bail!("Core's report-data.json does not hash to the report_data_sha256 it answered");
    }
    let run_json_bytes = pending(RUN_JSON_NAME).await?;
    let run_json: Value = serde_json::from_slice(&run_json_bytes).context("run.json is not JSON")?;
    let run_json_sha256 = sha256_hex(&run_json_bytes);
    // Each study run's measurements, at the pending revision: the exports read them and nothing else
    // of the zip besides `report-data.json`. A study that declared none has no such file.
    let mut measurement_bytes: BTreeMap<String, Vec<u8>> = BTreeMap::new();
    for id in study_ids_of(&rd.report_data) {
        let name = format!("studies/{id}/measurements.json");
        if let Some(b) = core.test_publish_file(run_id, revision, &name).await? {
            measurement_bytes.insert(id, b.to_vec());
        }
    }
    let mut measurements: BTreeMap<String, Value> = BTreeMap::new();
    for (id, b) in &measurement_bytes {
        measurements.insert(id.clone(), serde_json::from_slice(b).with_context(|| format!("studies/{id}/measurements.json is not JSON"))?);
    }

    let supersedes: Option<Supersedes> = (revision > 1).then(|| revision - 1).map(|r| Supersedes {
        revision: r,
        manifest_sha256: None,
        from_zip: false,
    });
    let supersedes = match supersedes {
        Some(mut s) => {
            s.manifest_sha256 = core.test_publish_file(run_id, s.revision, MANIFEST_NAME).await.ok().flatten().map(|b| sha256_hex(&b));
            Some(s)
        }
        None => None,
    };

    let report = report_source(&rd.report_data)?;
    let pins = RunPins {
        run_json_sha256: &run_json_sha256,
        plan_hash: run_json["plan_hash"].as_str(),
        revision,
        supersedes: supersedes.as_ref(),
    };
    let appendix = appendix_source(&rd.report_data, &pins);
    let mut staging = Staging::new()?;
    staging.stage_bytes(REPORT_DATA_NAME, &report_data_bytes)?;
    staging.stage_bytes(REPORT_FILE, report.as_bytes())?;
    staging.stage_bytes(APPENDIX_FILE, appendix.as_bytes())?;
    let pdf = render_report(&staging, &RenderOptions { ident: format!("{run_id}-r{revision}"), timestamp_unix: now_unix })?;

    let mut api: BTreeMap<String, Vec<u8>> = BTreeMap::new();
    api.insert(REPORT_PDF.into(), pdf);
    api.insert(REPORT_FILE.into(), report.into_bytes());
    let export = TestExportInputs { report_data: &rd.report_data, measurements: &measurements };
    api.insert(JUNIT_NAME.into(), junit_xml(&export).into_bytes());
    api.insert(OCP_NAME.into(), ocp_jsonl(&export).into_bytes());
    api.insert(APPENDIX_FILE.into(), appendix.into_bytes());
    let api_files: Vec<PublishFile> =
        api.iter().map(|(n, b)| PublishFile { name: n.clone(), sha256: sha256_hex(b) }).collect();

    let published = core.test_publish(run_id, &api_files).await.context("Core refused the Test run's publish")?;
    if published.revision != revision {
        bail!(
            "Core published revision {} but the report was built for revision {revision}: another publish raced this one. Nothing was written; publish again",
            published.revision
        );
    }

    let manifest_bytes = core
        .test_publish_file(run_id, revision, MANIFEST_NAME)
        .await?
        .ok_or_else(|| anyhow!("Core did not serve manifest.dsse.json for revision {revision}"))?;
    let mut core_files: BTreeMap<String, Vec<u8>> = BTreeMap::new();
    for (name, digest) in manifest_subjects(&manifest_bytes)? {
        let bytes = core
            .test_publish_file(run_id, revision, &name)
            .await?
            .ok_or_else(|| anyhow!("Core's manifest names {name} but did not serve it"))?;
        if sha256_hex(&bytes) != digest {
            bail!("Core served {name} with bytes that do not match the manifest's digest for it");
        }
        core_files.insert(name, bytes.to_vec());
    }
    core_files.insert(MANIFEST_NAME.to_string(), manifest_bytes.to_vec());

    // What the PDF read must be what Core signed.
    let read_files = [(REPORT_DATA_NAME.to_string(), &report_data_bytes[..]), (RUN_JSON_NAME.to_string(), &run_json_bytes[..])]
        .into_iter()
        .chain(measurement_bytes.iter().map(|(id, b)| (format!("studies/{id}/measurements.json"), &b[..])));
    for (name, read) in read_files {
        if core_files.get(&name).map(Vec::as_slice) != Some(read) {
            bail!("{name} changed between the render and the manifest, or the manifest does not name it; the PDF is built from other bytes");
        }
    }
    let mut entries = core_files;
    for (name, bytes) in api {
        if entries.insert(name.clone(), bytes).is_some() {
            bail!("embarch-api and Core both produced {name}; nothing was written");
        }
    }

    std::fs::create_dir_all(folder).with_context(|| format!("cannot create the publish folder {}", folder.display()))?;
    let name_slug = match rd.report_data["suite"]["id"].as_str() {
        Some(s) if !s.is_empty() => slug(s),
        _ => "test-run".to_string(),
    };
    let zip_path = folder.join(zip_name(&utc_date(now_unix), &name_slug, run_id, revision));
    let zip_sha256 = write_zip(&zip_path, &entries)?;
    Ok(PublishOutcome {
        zip: zip_path,
        zip_sha256,
        revision,
        manifest_sha256: sha256_hex(&manifest_bytes),
        report_source: ReportSource::Generated,
        files: entries.keys().cloned().collect(),
        embarch_api_files: api_files,
        supersedes,
        warnings: Vec::new(),
    })
}
