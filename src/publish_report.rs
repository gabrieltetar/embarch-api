//! The Typst sources `publish` writes itself (`embarch-api` decision 113): the
//! fixed audit appendix, and the data section a Study with no `report.typ`
//! publishes instead of one.
//!
//! Both are generated from `report-data.json` and `measurements.json` and
//! carry every value as a Typst **string literal** ([`lit`]), so nothing in a
//! run's data can be read as markup or code. They import no package. They are in
//! the zip as `appendix.typ` and `report.typ`, so the PDF is rebuilt from the
//! zip alone.

use serde_json::Value;

use crate::publish_export::{measurement_line, qualifiers, StepRow};

/// One capture the data section lists.
#[derive(Debug, Clone, PartialEq)]
pub struct CaptureRow {
    pub file: String,
    /// Data rows (a CSV's lines less its header; a text capture's lines).
    pub rows: u64,
}

/// Which `report.typ` the PDF was built from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReportSource {
    /// The study's own.
    Study,
    /// The data section this crate generates, since the study has none.
    Generated,
}

impl ReportSource {
    pub fn as_str(&self) -> &'static str {
        match self {
            ReportSource::Study => "the study's own report.typ",
            ReportSource::Generated => "generated by embarch-api (the study has no report.typ)",
        }
    }
}

pub struct ReportInputs<'a> {
    pub report_data: &'a Value,
    pub measurements: Option<&'a Value>,
    pub steps: &'a [StepRow],
    pub captures: &'a [CaptureRow],
    /// The operator's notes, verbatim.
    pub notes: Option<&'a str>,
    pub revision: u64,
    pub api_version: &'a str,
    pub typst_version: &'a str,
    pub source: ReportSource,
}

/// A Typst string literal for `s`.
pub fn lit(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 || c as u32 == 0x7f => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn show(v: &Value) -> String {
    match v {
        Value::Null => "none".to_string(),
        Value::String(s) => s.clone(),
        other => other.to_string(),
    }
}

fn at(v: &Value, pointer: &str) -> String {
    v.pointer(pointer).map(show).unwrap_or_else(|| "not recorded".to_string())
}

struct Doc(String);

impl Doc {
    fn new() -> Self {
        Doc(String::new())
    }
    fn heading(&mut self, level: usize, text: &str) {
        self.0.push_str(&format!("#heading(level: {level}, {})\n", lit(text)));
    }
    fn para(&mut self, text: &str) {
        self.0.push_str(&format!("#par({})\n\n", lit(text)));
    }
    fn table(&mut self, cols: &[&str], rows: &[Vec<String>]) {
        let n = cols.len();
        let spec = if n == 2 { "(auto, 1fr)".to_string() } else { format!("{n}") };
        self.0.push_str(&format!("#table(columns: {spec}, stroke: 0.4pt, inset: 3pt,\n"));
        for c in cols {
            self.0.push_str(&format!("  table.cell(fill: luma(230), strong({})),\n", lit(c)));
        }
        for r in rows {
            for c in r {
                self.0.push_str(&format!("  {},\n", lit(c)));
            }
        }
        self.0.push_str(")\n\n");
    }
    fn kv(&mut self, rows: &[(&str, String)]) {
        let rows: Vec<Vec<String>> = rows.iter().map(|(k, v)| vec![(*k).to_string(), v.clone()]).collect();
        self.table(&["Item", "Value"], &rows);
    }
}

fn measurement_rows(ms: Option<&Value>) -> Vec<Vec<String>> {
    ms.and_then(|m| m["measurements"].as_array())
        .into_iter()
        .flatten()
        .map(|m| {
            let source = &m["source"];
            let src = match (source["rows"].as_array(), source["bytes"].as_array()) {
                (Some(r), _) => format!("{} rows {}-{}", show(&source["file"]), show(&r[0]), show(&r[1])),
                (_, Some(b)) => format!("{} bytes {}+{}", show(&source["file"]), show(&b[0]), show(&b[1])),
                _ => show(&source["step"]),
            };
            let incomplete: Vec<String> =
                m["incomplete"].as_array().into_iter().flatten().map(show).collect();
            vec![
                show(&m["name"]),
                measurement_line(m),
                show(&m["by"]),
                show(&m["bench_image"]),
                show(&m["u_source"]),
                src,
                if incomplete.is_empty() { "complete".into() } else { incomplete.join(", ") },
            ]
        })
        .collect()
}

const MEASUREMENT_COLS: [&str; 7] = ["Name", "Value", "By", "Bench image", "U source", "Source", "Incomplete"];

/// The data section: the report of a Study that has no `report.typ`.
pub fn data_section_source(i: &ReportInputs) -> String {
    let mut d = Doc::new();
    d.0.push_str("#set text(size: 10pt)\n");
    d.0.push_str(&format!("#title({})\n", lit(&format!("Study report: {}", at(i.report_data, "/subject/study_name")))));
    d.para(&format!("Run status: {}. This study carries no report.typ, so this section lists its data.", at(i.report_data, "/run_status")));
    d.heading(1, "Data");
    d.heading(2, "Captures");
    if i.captures.is_empty() {
        d.para("No capture was rendered for this run.");
    } else {
        let rows: Vec<Vec<String>> = i.captures.iter().map(|c| vec![c.file.clone(), c.rows.to_string()]).collect();
        d.table(&["File", "Rows"], &rows);
    }
    d.heading(2, "Measurements");
    let rows = measurement_rows(i.measurements);
    if rows.is_empty() {
        d.para("This study declared no measurement, or Core did not serve measurements.json before publish.");
    } else {
        d.table(&MEASUREMENT_COLS, &rows);
    }
    d.0
}

/// The fixed audit appendix, the rows of `notes/hil/06-report-and-publish.md`
/// that apply to a Study. A row Core's data does not yet hold says so.
pub fn appendix_source(i: &ReportInputs) -> String {
    let rd = i.report_data;
    let mut d = Doc::new();
    d.0.push_str("#set text(size: 9pt)\n");
    d.heading(1, "Audit appendix");
    d.para("Appended by embarch-api to every report. Core's signed manifest lists every file of this zip it produced; the files embarch-api made are listed in it as embarch-api's and are checked by verify, not by Core's signature.");

    d.heading(2, "Observed by Core");
    d.kv(&[
        ("Run", at(rd, "/study_id")),
        ("Run status", at(rd, "/run_status")),
        (
            "Steps",
            format!(
                "{} total, {} pass, {} fail, {} timed out, {} other",
                at(rd, "/steps/total"),
                at(rd, "/steps/pass"),
                at(rd, "/steps/fail"),
                at(rd, "/steps/timed_out"),
                at(rd, "/steps/other")
            ),
        ),
        ("DUT image status", at(rd, "/observed/image_status")),
        ("Declarations", at(rd, "/observed/declarations")),
        ("Core version", at(rd, "/core/version")),
        ("Core key id", at(rd, "/core/keyid")),
        ("Signed record SHA-256", at(rd, "/record_sha256")),
    ]);

    d.heading(2, "Claimed by the build");
    d.para("What embarch-api reported, which the agent can reach: a claim.");
    d.kv(&[("Build", at(rd, "/claimed/build"))]);

    d.heading(2, "Pinned inputs");
    d.kv(&[
        ("Study", at(rd, "/subject/study_name")),
        ("Subject provenance", at(rd, "/subject/provenance")),
        ("Revision", i.revision.to_string()),
        ("embarch-api version", i.api_version.to_string()),
        ("Typst version", i.typst_version.to_string()),
        ("report.typ", i.source.as_str().to_string()),
    ]);

    d.heading(2, "Attestation");
    d.kv(&[
        ("Label", at(rd, "/attestation/label")),
        ("Core attested", at(rd, "/attestation/core_attested")),
        ("Reason", at(rd, "/attestation/reason")),
        ("Run begun with", at(rd, "/go_by")),
        ("Published by", at(rd, "/published_by")),
        ("Qualifiers", qualifiers(rd, i.measurements).join(", ")),
    ]);

    d.heading(2, "Measurements");
    let rows = measurement_rows(i.measurements);
    if rows.is_empty() {
        d.para("None: the study declared no measurement, or measurements.json was not available when this report was built.");
    } else {
        d.table(&MEASUREMENT_COLS, &rows);
    }

    d.heading(2, "The study design");
    d.para("The study as submitted is study.json in this zip. Its steps and their outcomes:");
    let rows: Vec<Vec<String>> = i
        .steps
        .iter()
        .map(|s| vec![s.name.clone(), s.outcome.clone(), s.reason.clone().unwrap_or_default()])
        .collect();
    if rows.is_empty() {
        d.para("No step record was available.");
    } else {
        d.table(&["Step", "Outcome", "Reason"], &rows);
    }

    d.heading(2, "Notes and prose");
    let adopted: Vec<Vec<String>> = rd["adopted"]
        .as_array()
        .into_iter()
        .flatten()
        .map(|a| {
            vec![
                show(&a["kind"]),
                show(&a["name"]),
                show(&a["attribution"]),
                show(&a["scope"]),
                show(&a["text_sha256"]),
            ]
        })
        .collect();
    if adopted.is_empty() {
        d.para("No note or prose block was adopted for this run.");
    } else {
        d.table(&["Kind", "File", "Attribution", "Token scope", "Text SHA-256"], &adopted);
    }
    if let Some(n) = i.notes {
        d.heading(2, "Operator and setup notes");
        d.para(n);
    }

    d.heading(2, "Limits and losses");
    let mut lost = Vec::new();
    for m in i.measurements.and_then(|m| m["measurements"].as_array()).into_iter().flatten() {
        if m["incomplete"].as_array().is_some_and(|a| !a.is_empty()) {
            lost.push(vec![show(&m["name"]), show(&m["incomplete"])]);
        }
    }
    if lost.is_empty() {
        d.para("No measurement is marked incomplete.");
    } else {
        d.table(&["Measurement", "Incomplete"], &lost);
    }
    d.para("Not carried in milestone 1: a call log (this zip has none), the image readback, an instrument's identity, runs of the same study on the same unit, definition files other than the study file. Each is a claim or an absence, never a pass.");

    d.heading(2, "Hash manifest");
    d.para(&format!("manifest.dsse.json, signed by Core, holds the SHA-256 of every file of this zip. This is revision {}.", i.revision));
    d.0
}

